class Egypt():
    def capital(self):
        print("Cairo is the capital of Egypt")
    
    def language(self):        
        print("The official language of Egypt is Arabic")
    
    def population(self):
        print("The population of Egypt is approximately 120 million people")

class India():
    def capital(self):
        print("New Delhi is the capital of India")
    
    def language(self):        
        print("The official language of India are Hindi ")
    
    def population(self):
        print("The population of India is approximately 1.4 billion people")

